LANGUAGE_NAMES = {
    "zh": "Simplified Chinese",
    "ko": "Korean",
}

lock = threading.Lock()


def read_glosses(db_path: pathlib.Path) -> dict[str, str]:
    db = sqlite3.connect(db_path)
    try:
        rows = db.execute(
            "SELECT strongs_id, gloss FROM lexicon "
            "WHERE strongs_id IS NOT NULL AND strongs_id != '' "
            "AND gloss IS NOT NULL AND gloss != ''"
        ).fetchall()
    finally:
        db.close()

    best: dict[str, str] = {}
    for strongs_id, gloss in rows:
        gloss = gloss.strip()
        if not gloss:
            continue
        current = best.get(strongs_id)
        if current is None or len(gloss) < len(current):
            best[strongs_id] = gloss
    return best


def load_cache(lang: str) -> dict[str, str]:
    path = CACHE_DIR / f"{lang}.json"
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as handle:
        data = json.load(handle)
    return {k: v for k, v in data.items() if not k.startswith("_")}


def save_cache(lang: str, entries: dict[str, str]) -> None:
    with lock:
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        path = CACHE_DIR / f"{lang}.json"
        payload = {
            "_comment": (
                f"Machine-translated lexicon glosses ({LANGUAGE_NAMES[lang]}), "
                "keyed by Strong's id. Generated by scripts/translate_glosses.py; "
                "safe to hand-correct — the script never overwrites an existing "
                "key."
            ),
            **dict(sorted(entries.items())),
        }
        tmp = path.with_suffix(".json.tmp")
        with tmp.open("w", encoding="utf-8") as handle:
            json.dump(payload, handle, ensure_ascii=False, indent=1)
            handle.write("\n")
        tmp.replace(path)


def request_batch(api_key: str, lang: str, batch: dict[str, str], timeout: int = 45) -> dict[str, str]:
    body = {
        "model": MODEL,
        "temperature": 0,
        "messages": [
            {"role": "system", "content": PROMPTS[lang]},
            {"role": "user", "content": json.dumps(batch, ensure_ascii=False)},
        ],
    }

    req = urllib.request.Request(
        ENDPOINT,
        data=json.dumps(body).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
    )

    with urllib.request.urlopen(req, timeout=timeout) as response:
        payload = json.loads(response.read().decode("utf-8"))

    content = payload["choices"][0]["message"]["content"].strip()
    if content.startswith("```"):
        content = content.split("\n", 1)[1].rsplit("```", 1)[0]

    parsed = json.loads(content)
    if not isinstance(parsed, dict):
        raise ValueError("response is not a dict")

    return {
        k: str(v).strip()
        for k, v in parsed.items()
        if k in batch and str(v).strip()
    }


def translate_sub_batch(api_key: str, lang: str, batch: dict[str, str], batch_idx: int, total_batches: int) -> dict[str, str]:
    t0 = time.time()
    for attempt in range(1, 5):
        try:
            res = request_batch(api_key, lang, batch)
            missing = {k: v for k, v in batch.items() if k not in res}
            if missing:
                for sub_attempt in range(1, 3):
                    try:
                        recovered = request_batch(api_key, lang, missing)
                        res.update(recovered)
                        break
                    except Exception:
                        time.sleep(1.0)
            dt = time.time() - t0
            print(f"[{lang}] Batch {batch_idx}/{total_batches} finished in {dt:.1f}s (+{len(res)}/{len(batch)} items)", flush=True)
            return res
        except Exception as e:
            wait_time = attempt * 2.0
            print(f"[{lang}] Batch {batch_idx}/{total_batches} error (attempt {attempt}/4): {e}, retrying in {wait_time}s...", flush=True)
            time.sleep(wait_time)
    raise RuntimeError(f"[{lang}] Failed to translate batch {batch_idx}")


def translate_all_for_lang(lang: str, glosses: dict[str, str], api_key: str, batch_size: int = 50, max_workers: int = 5) -> None:
    cache = load_cache(lang)
    pending = {k: v for k, v in glosses.items() if k not in cache}
    print(f"[{lang}] Total glosses: {len(glosses)}, Cached: {len(cache)}, Pending: {len(pending)}", flush=True)
    
    if not pending:
        print(f"[{lang}] 100% already translated!", flush=True)
        return

    items = list(pending.items())
    batches = [dict(items[i : i + batch_size]) for i in range(0, len(items), batch_size)]
    total_batches = len(batches)
    completed_batches = 0

    print(f"[{lang}] Dispatching {total_batches} batches with {max_workers} worker threads...", flush=True)

    with ThreadPoolExecutor(max_workers=max_workers) as executor:
        future_to_batch = {
            executor.submit(translate_sub_batch, api_key, lang, b, idx + 1, total_batches): (idx, b)
            for idx, b in enumerate(batches)
        }

        for future in as_completed(future_to_batch):
            idx, b = future_to_batch[future]
            try:
                result = future.result()
                with lock:
                    cache.update(result)
                    save_cache(lang, cache)
                    completed_batches += 1
                    if completed_batches % 5 == 0 or completed_batches == total_batches:
                        pct = len(cache) / len(glosses) * 100
                        print(f"[{lang}] Progress: {completed_batches}/{total_batches} batches done, cache={len(cache)}/{len(glosses)} ({pct:.1f}%)", flush=True)
            except Exception as e:
                print(f"[{lang}] Batch {idx+1} error: {e}", flush=True)

    # Final verification & cleanup pass for any dropped keys
    cache = load_cache(lang)
    still_pending = {k: v for k, v in glosses.items() if k not in cache}
    if still_pending:
        print(f"[{lang}] Clean-up pass for {len(still_pending)} remaining items...", flush=True)
        cleanup_batches = [dict(list(still_pending.items())[i : i + 20]) for i in range(0, len(still_pending), 20)]
        for cb in cleanup_batches:
            try:
                res = translate_sub_batch(api_key, lang, cb)
                with lock:
                    cache.update(res)
                    save_cache(lang, cache)
            except Exception as e:
                print(f"[{lang}] Error in cleanup batch: {e}", flush=True)

    print(f"[{lang}] Final translation count: {len(cache)}/{len(glosses)} ({len(cache)/len(glosses)*100:.2f}%)", flush=True)


def main():
    api_key = openrouter_api_key()
    if not api_key:
        print("Missing OpenRouter API key!", file=sys.stderr)
        sys.exit(1)

    glosses = read_glosses(DB_PATH)
    print(f"Loaded {len(glosses)} unique Strong's glosses from {DB_PATH}", flush=True)

    # Run zh then ko
    for lang in ["zh", "ko"]:
        print(f"\n==========================================", flush=True)
        print(f"   Translating {LANGUAGE_NAMES[lang]} ({lang})", flush=True)
        print(f"==========================================", flush=True)
        translate_all_for_lang(lang, glosses, api_key, batch_size=50, max_workers=6)

    print("\n==========================================", flush=True)
    print("   Final Validation Report", flush=True)
    print("==========================================", flush=True)
    for lang in ["zh", "ko"]:
        cache = load_cache(lang)
        pct = len(cache) / len(glosses) * 100
        print(f"[{lang}] {len(cache)} / {len(glosses)} ({pct:.2f}%)", flush=True)


if __name__ == "__main__":
    main()
