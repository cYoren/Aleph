#!/usr/bin/env python3
"""Translate the lexicon's short glosses into the app's other 7 languages.

Why this exists
---------------
`lexicon.gloss` is the one- or two-word meaning shown everywhere in the reader:
the definition sheet, the long-press peek, reader-mode inline glosses, the
vocabulary deck, and word search. There are 13,433 of them, about 99k
characters in total — small enough to translate once, far too many to translate
by hand, and pointless to re-pay for on every database rebuild.

So this script is the cheap half of the job:

  * It translates only `gloss`, never `definition` or `extended_definition`.
    The scholarly entries are an order of magnitude larger, and a beginner
    reads the gloss.
  * It batches many glosses into one request, since each is a couple of words.
  * It writes to a **tracked cache** under `data/gloss_translations/<lang>.json`
    and never asks for a gloss that is already there, so an interrupted run
    resumes for free and a rebuilt database costs nothing.
  * It defaults to a free model.

Usage
-----
Supply the key once, either way:

    export OPENROUTER_API_KEY=sk-or-v1-...     # this shell only
    echo 'OPENROUTER_API_KEY=sk-or-v1-...' >> .env   # gitignored, survives

    # one language, dry run first to see the cost/shape
    python3 scripts/translate_glosses.py --languages pt --limit 50

    # the real thing
    python3 scripts/translate_glosses.py

    # then fold the cache into the database
    python3 scripts/apply_gloss_translations.py

The database is a generated artifact and is not committed; the cache under
`data/` is the durable output and should be.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sqlite3
import sys
import time
import urllib.error
import urllib.request

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from _secrets import MISSING_MESSAGE, openrouter_api_key  # noqa: E402

REPO = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_DB = REPO / "assets" / "bible.db"
CACHE_DIR = REPO / "data" / "gloss_translations"

ENDPOINT = "https://openrouter.ai/api/v1/chat/completions"

# Free tier, and the same model the in-app explanation feature uses. Keep it
# free unless someone deliberately opts into a paid one.
DEFAULT_MODEL = "nvidia/nemotron-3.5-lightning:free"

LANGUAGE_NAMES = {
    "pt": "Brazilian Portuguese",
    "de": "German",
    "fr": "French",
    "es": "Spanish",
    "ru": "Russian",
    "zh": "Simplified Chinese",
    "ko": "Korean",
}

SYSTEM_PROMPT = """You translate short dictionary glosses for a Bible study app.

Each input is the one- or two-word English meaning of a Hebrew or Greek word,
as printed in a concordance. Translate each into {language}.

Rules:
- Keep it as short as the English. A gloss is a label, not a definition.
- Translate the sense a lexicon intends. "LORD" (God's covenant name) is not
  the same as "lord" (a human master); divine titles (Lord, God, Almighty) keep
  their capitalization in the target language (e.g. "Senhor", "Señor", "Herr").
- Keep the part of speech and verbal aspect. English participles or phrasal
  verbs like "set apart" or "to separate" are verbs and must stay verbs in the
  target language (e.g. "separar" / "dividir", not an adjective like "santo").
  An English infinitive like "to walk" stays an infinitive; a plural stays plural.
- Leave proper names (people, places) in their conventional {language} biblical
  form; if you are unsure, leave the name unchanged.
- Leave anything in parentheses, and any bare grammatical marker such as "(et)",
  exactly as it is.
- Never add commentary, transliteration, or alternatives.

Return ONLY a JSON object mapping each input id to its translated string. No
prose, no code fence."""


def load_cache(lang: str) -> dict[str, str]:
    path = CACHE_DIR / f"{lang}.json"
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as handle:
        data = json.load(handle)
    return {k: v for k, v in data.items() if not k.startswith("_")}


def save_cache(lang: str, entries: dict[str, str]) -> None:
    CACHE_DIR.mkdir(parents=True, exist_ok=True)
    path = CACHE_DIR / f"{lang}.json"
    payload = {
        "_comment": (
            f"Machine-translated lexicon glosses ({LANGUAGE_NAMES[lang]}), "
            "keyed by Strong's id. Generated by scripts/translate_glosses.py; "
            "safe to hand-correct — the script never overwrites an existing "
            "key."
        ),
        **dict(sorted(entries.items())),
    }
    tmp = path.with_suffix(".json.tmp")
    with tmp.open("w", encoding="utf-8") as handle:
        json.dump(payload, handle, ensure_ascii=False, indent=1)
        handle.write("\n")
    tmp.replace(path)


def read_glosses(db_path: pathlib.Path) -> dict[str, str]:
    """One English gloss per Strong's id.

    Several lemma rows can share a Strong's id (inflected forms). The shortest
    gloss is the most label-like, so it wins.
    """
    db = sqlite3.connect(db_path)
    try:
        rows = db.execute(
            "SELECT strongs_id, gloss FROM lexicon "
            "WHERE strongs_id IS NOT NULL AND strongs_id != '' "
            "AND gloss IS NOT NULL AND gloss != ''"
        ).fetchall()
    finally:
        db.close()

    best: dict[str, str] = {}
    for strongs_id, gloss in rows:
        gloss = gloss.strip()
        if not gloss:
            continue
        current = best.get(strongs_id)
        if current is None or len(gloss) < len(current):
            best[strongs_id] = gloss
    return best


def request_batch(
    api_key: str,
    model: str,
    language: str,
    batch: dict[str, str],
    timeout: int,
) -> dict[str, str]:
    body = {
        "model": model,
        # The model this defaults to is a reasoning model that will otherwise
        # print its own thinking as the answer — see queue.md, Task 4.
        "reasoning": {"exclude": True},
        "max_tokens": 8192,
        "temperature": 0,
        "messages": [
            {
                "role": "system",
                "content": SYSTEM_PROMPT.format(language=LANGUAGE_NAMES[language]),
            },
            {
                "role": "user",
                "content": json.dumps(batch, ensure_ascii=False),
            },
        ],
    }

    request = urllib.request.Request(
        ENDPOINT,
        data=json.dumps(body).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
    )

    with urllib.request.urlopen(request, timeout=timeout) as response:
        payload = json.loads(response.read().decode("utf-8"))

    content = payload["choices"][0]["message"]["content"].strip()
    if content.startswith("```"):
        content = content.split("\n", 1)[1].rsplit("```", 1)[0]

    parsed = json.loads(content)
    if not isinstance(parsed, dict):
        raise ValueError("model did not return a JSON object")

    # Only keep ids we actually asked about, and only non-empty strings.
    return {
        key: value.strip()
        for key, value in parsed.items()
        if key in batch and isinstance(value, str) and value.strip()
    }


def translate_language(
    lang: str,
    glosses: dict[str, str],
    api_key: str,
    args: argparse.Namespace,
) -> None:
    cache = load_cache(lang)
    pending = {k: v for k, v in glosses.items() if k not in cache}
    if args.limit:
        pending = dict(list(pending.items())[: args.limit])

    if not pending:
        print(f"[{lang}] nothing to do ({len(cache)} cached)")
        return

    print(
        f"[{lang}] {len(pending)} to translate, {len(cache)} already cached, "
        f"batch size {args.batch_size}"
    )

    items = list(pending.items())
    failures = 0

    for start in range(0, len(items), args.batch_size):
        batch = dict(items[start : start + args.batch_size])

        for attempt in range(1, args.retries + 1):
            try:
                result = request_batch(
                    api_key, args.model, lang, batch, args.timeout
                )
                missing = set(batch) - set(result)
                cache.update(result)
                save_cache(lang, cache)
                print(
                    f"[{lang}] {start + len(batch)}/{len(items)} "
                    f"(+{len(result)}"
                    + (f", {len(missing)} skipped by model" if missing else "")
                    + ")"
                )
                break
            except (urllib.error.HTTPError, urllib.error.URLError) as exc:
                status = getattr(exc, "code", None)

                # A rejected key is not a transient failure. Retrying it four
                # times with backoff just wastes a minute and a half before
                # telling the operator the one thing they needed to hear.
                if status in (401, 403):
                    print(
                        f"[{lang}] the API key was rejected ({status}). Check "
                        "OPENROUTER_API_KEY, then re-run — nothing translated "
                        "so far is lost.",
                        file=sys.stderr,
                    )
                    return

                wait = args.backoff * attempt
                print(
                    f"[{lang}] batch at {start} failed ({status or exc}); "
                    f"retry {attempt}/{args.retries} in {wait}s",
                    file=sys.stderr,
                )
                time.sleep(wait)
            except (ValueError, KeyError, json.JSONDecodeError) as exc:
                print(
                    f"[{lang}] batch at {start} returned unusable output "
                    f"({exc}); retry {attempt}/{args.retries}",
                    file=sys.stderr,
                )
                time.sleep(args.backoff)
        else:
            failures += 1
            print(f"[{lang}] giving up on batch at {start}", file=sys.stderr)

        time.sleep(args.delay)

    print(f"[{lang}] done: {len(cache)} cached, {failures} batches unresolved")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--db", type=pathlib.Path, default=DEFAULT_DB)
    parser.add_argument(
        "--languages",
        default=",".join(LANGUAGE_NAMES),
        help="comma-separated locales to fill (default: all seven)",
    )
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument(
        "--batch-size",
        type=int,
        default=15,
        help="glosses per request; lower it if the model truncates",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=0,
        help="stop after this many glosses per language (0 = no limit)",
    )
    parser.add_argument("--timeout", type=int, default=180)
    parser.add_argument("--retries", type=int, default=4)
    parser.add_argument(
        "--delay",
        type=float,
        default=1.5,
        help="seconds between requests; the free tier rate-limits",
    )
    parser.add_argument("--backoff", type=float, default=8.0)
    args = parser.parse_args()

    api_key = openrouter_api_key()
    if not api_key:
        print(MISSING_MESSAGE, file=sys.stderr)
        return 2

    if not args.db.exists():
        print(f"No database at {args.db}. Build it first.", file=sys.stderr)
        return 2

    languages = [
        lang.strip() for lang in args.languages.split(",") if lang.strip()
    ]
    unknown = [lang for lang in languages if lang not in LANGUAGE_NAMES]
    if unknown:
        print(f"Unknown language(s): {', '.join(unknown)}", file=sys.stderr)
        return 2

    glosses = read_glosses(args.db)
    print(f"{len(glosses)} distinct Strong's ids carry a gloss")

    for lang in languages:
        translate_language(lang, glosses, api_key, args)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
